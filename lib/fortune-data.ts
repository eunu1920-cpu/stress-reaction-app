/** 날짜·띠 시드로 매일 랜덤하게 풀에서 한 세트 선택. 같은 날이라도 띠별로 다른 세트. */
export function getFortuneForToday(zodiacId?: string): FortuneSet {
  const now = new Date()
  const dateSeed = `${now.getFullYear()}-${now.getMonth()}-${now.getDate()}`
  const seed = zodiacId ? `${dateSeed}-${zodiacId}` : dateSeed
  let hash = 0
  for (let i = 0; i < seed.length; i++) {
    const char = seed.charCodeAt(i)
    hash = (hash << 5) - hash + char
    hash = hash & hash
  }
  const idx = Math.abs(hash) % FORTUNE_POOL.length
  return FORTUNE_POOL[idx]
}
